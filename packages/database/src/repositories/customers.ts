import type { Customer } from '../generated/prisma/client.js';
import type { TenantTx } from '../with-tenant.js';

export const customers = {
  async findById(tx: TenantTx, tenantId: string, id: string): Promise<Customer | null> {
    return tx.customer.findUnique({ where: { tenantId_id: { tenantId, id } } });
  },

  /** Lookup only (no create): the tenant's own record for this sender address, if the person has written. */
  async findByExternalRef(tx: TenantTx, tenantId: string, externalRef: string): Promise<Customer | null> {
    return tx.customer.findUnique({ where: { tenantId_externalRef: { tenantId, externalRef } } });
  },

  /**
   * One customer record per (tenant, person) (D-001). The ID is random and generated by the database;
   * it is never derived from `externalRef`, so the same person gets a different ID in each tenant.
   */
  async findOrCreateByExternalRef(tx: TenantTx, tenantId: string, externalRef: string): Promise<Customer> {
    return tx.customer.upsert({
      where: { tenantId_externalRef: { tenantId, externalRef } },
      create: { tenantId, externalRef },
      update: {},
    });
  },
};
